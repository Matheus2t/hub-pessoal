from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter


def background(width: int, height: int, rng: random.Random, kind: str) -> Image.Image:
    gen = np.random.default_rng(rng.randrange(2**32))
    yy, xx = np.mgrid[:height, :width]
    base = 105 + 35 * np.sin((xx + yy) / 55)
    if kind == "clutter":
        grid = gen.integers(40, 211, size=(height // 12 + 1, width // 12 + 1))
        base = grid[yy // 12, xx // 12]
    noise = gen.integers(-22, 23, size=(height, width))
    level = np.clip(base + noise, 0, 255)
    arr = np.stack((np.clip(level + 22, 0, 255), level, np.clip(level - 10, 0, 255)), axis=-1).astype(np.uint8)
    image = Image.fromarray(arr, "RGB")
    draw = ImageDraw.Draw(image)
    if kind in {"clutter", "fine_edges"}:
        for _ in range(85):
            x, y = rng.randrange(width), rng.randrange(height)
            color = tuple(rng.randrange(20, 230) for _ in range(3))
            draw.line((x, y, x + rng.randrange(-45, 46), y + rng.randrange(-45, 46)), fill=color, width=rng.randrange(1, 5))
    return image


def make_sample(root: Path, index: int) -> dict:
    rng = random.Random(27000 + index)
    width, height = [(512, 512), (640, 480), (480, 640)][index % 3]
    kinds = ["fine_edges", "translucency", "low_contrast", "clutter", "thin_geometry"]
    kind = kinds[index % len(kinds)]
    bg = background(width, height, rng, kind)
    scale = 3
    mask_hi = Image.new("L", (width * scale, height * scale), 0)
    draw = ImageDraw.Draw(mask_hi)
    color = (124, 131, 139)
    shade = 0.5 if kind == "translucency" else 1.0
    if kind == "low_contrast":
        color = (140, 133, 128)
    if kind == "thin_geometry":
        # Spokes and narrow appendages stress edge retention.
        cx, cy = width // 2, height // 2
        for angle in range(0, 360, 30):
            import math
            r1, r2 = min(width, height) * .10, min(width, height) * .34
            x1, y1 = cx + int(r1 * math.cos(math.radians(angle))), cy + int(r1 * math.sin(math.radians(angle)))
            x2, y2 = cx + int(r2 * math.cos(math.radians(angle))), cy + int(r2 * math.sin(math.radians(angle)))
            draw.line((x1*scale, y1*scale, x2*scale, y2*scale), fill=255, width=3*scale)
        draw.ellipse(((cx-72)*scale, (cy-72)*scale, (cx+72)*scale, (cy+72)*scale), fill=255)
    elif kind == "fine_edges":
        # A head-like silhouette with thin branching contours; wholly synthetic.
        draw.ellipse((205*scale, 72*scale, 332*scale, 218*scale), fill=255)
        draw.polygon([(155*scale, 470*scale), (178*scale, 260*scale), (240*scale, 200*scale), (320*scale, 250*scale), (383*scale, 470*scale)], fill=255)
        for _ in range(24):
            x = rng.randrange(200, 340)
            y = rng.randrange(65, 220)
            draw.line((x*scale, y*scale, (x+rng.randrange(-45, 46))*scale, (y-rng.randrange(5, 65))*scale), fill=255, width=rng.choice([1, 2, 3])*scale)
    else:
        x0 = rng.randrange(width // 5, width // 3)
        x1 = rng.randrange(width * 2 // 3, width * 4 // 5)
        y0 = rng.randrange(height // 8, height // 4)
        y1 = rng.randrange(height * 3 // 4, height * 7 // 8)
        draw.ellipse((x0*scale, y0*scale, x1*scale, y1*scale), fill=255)
        draw.polygon([(x0*scale, (y0+60)*scale), ((x0-30)*scale, y1*scale), ((x1+20)*scale, y1*scale), ((x1-10)*scale, (y0+70)*scale)], fill=255)
        if kind == "translucency":
            # Foreground pixels are composited with known constant partial alpha.
            draw.ellipse(((x0+26)*scale, (y0+30)*scale, (x1-26)*scale, (y1-45)*scale), fill=128)
    mask = mask_hi.resize((width, height), Image.Resampling.LANCZOS)
    alpha = np.asarray(mask, dtype=np.float32) / 255.0
    # For translucent samples, model a soft/partly transparent subject everywhere.
    if shade < 1:
        alpha = np.where(alpha > 0.02, alpha * shade, alpha)
        mask = Image.fromarray(np.round(alpha * 255).astype(np.uint8), "L")
    fg = Image.new("RGB", (width, height), color)
    rgb = np.asarray(bg, dtype=np.float32)
    fg_rgb = np.asarray(fg, dtype=np.float32)
    composed = np.clip(rgb * (1 - alpha[..., None]) + fg_rgb * alpha[..., None], 0, 255).astype(np.uint8)
    image = Image.fromarray(composed, "RGB")
    image_path = root / "synthetic" / f"syn-{index+1:03d}.png"
    mask_path = root / "synthetic" / f"syn-{index+1:03d}-alpha.png"
    image.save(image_path)
    mask.save(mask_path)
    return {
        "id": f"synthetic-{index+1:03d}",
        "source": "2T deterministic procedural generator; no external image assets",
        "source_id": f"synthetic-seed-{27000+index}",
        "source_url": None,
        "license": "CC0-1.0; generated by benchmark script",
        "category": f"synthetic-{kind}",
        "image": f"synthetic/{image_path.name}",
        "ground_truth": f"synthetic/{mask_path.name}",
        "ground_truth_type": "continuous alpha matte",
        "size": {"width": width, "height": height},
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1] / "data")
    parser.add_argument("--count", type=int, default=40)
    args = parser.parse_args()
    target = args.root / "synthetic"
    target.mkdir(parents=True, exist_ok=True)
    rows = [make_sample(args.root, i) for i in range(args.count)]
    (target / "synthetic-items.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    print(f"generated {len(rows)} synthetic image/matte pairs under {target}")


if __name__ == "__main__":
    main()
