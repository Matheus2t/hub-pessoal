export const normalizeSearch = (value: string) => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toUpperCase();
export const findStock = (value: string) => stocks.find(stock => stock.symbol === normalizeSearch(value));
export const searchStocks = (value: string, sector = '', order: 'symbol' | 'name' = 'symbol') => stocks
  .filter(stock => (!sector || stock.sector === sector) && normalizeSearch(`${stock.symbol} ${stock.name}`).includes(normalizeSearch(value)))
  .sort((a, b) => a[order].localeCompare(b[order], 'pt-BR') || a.symbol.localeCompare(b.symbol));
