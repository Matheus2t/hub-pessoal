import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLI_VERSION = "3.2.0";
const RUNTIME = join(ROOT, "tests", "mind-codespaces-runtime");
const BACKEND = join(ROOT, "backend");
const ENV_FILE = join(BACKEND, ".env");
const ENV_MARKER = "# Generated by scripts/mind-codespaces.mjs; local-only.\n";
const ADMIN_FILE = join(BACKEND, ".mind-codespaces-admin.json");
const KEY_FILE = join(BACKEND, ".mind-codespaces-encryption-key");
const LOCAL_ORIGIN = "http://localhost:3000";
const REDIRECT_URI = "http://localhost:8000/api/mind-drive/google/callback";

export function parseSupabaseStatusEnv(text) {
  const values = {};
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)=(.*)\s*$/);
    if (!match) continue;
    const raw = match[2].trim();
    try {
      values[match[1]] = raw.startsWith('"') ? JSON.parse(raw) : raw.replace(/^'(.*)'$/, "$1");
    } catch {
      throw new Error("Supabase CLI retornou configuração local ilegível.");
    }
  }
  return values;
}

function jwtRole(value) {
  try { return JSON.parse(Buffer.from(value.split(".")[1], "base64url").toString("utf8")).role; }
  catch { return null; }
}

export function buildLocalBackendEnv(status, secrets, encryptionKey) {
  const apiUrl = status.API_URL;
  const anonKey = status.ANON_KEY;
  const serviceRoleKey = status.SERVICE_ROLE_KEY;
  if (apiUrl !== "http://127.0.0.1:54321" || jwtRole(anonKey) !== "anon" || jwtRole(serviceRoleKey) !== "service_role") {
    throw new Error("Supabase local não retornou URL e chaves locais válidas; configuração recusada.");
  }
  const rotated = secrets.TWO_T_GOOGLE_OAUTH_ROTATED === "yes";
  const clientId = secrets.TWO_T_GOOGLE_DRIVE_CLIENT_ID ?? "";
  const clientSecret = secrets.TWO_T_GOOGLE_DRIVE_CLIENT_SECRET ?? "";
  const driveEnabled = rotated && Boolean(clientId && clientSecret);
  if (Buffer.from(encryptionKey, "base64").length !== 32) throw new Error("Chave local de criptografia inválida.");
  return {
    MIND_GOOGLE_DRIVE_ENABLED: String(driveEnabled),
    MIND_SUPABASE_URL: apiUrl,
    MIND_SUPABASE_PUBLISHABLE_KEY: anonKey,
    MIND_SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey,
    GOOGLE_DRIVE_CLIENT_ID: clientId,
    GOOGLE_DRIVE_CLIENT_SECRET: clientSecret,
    GOOGLE_DRIVE_REDIRECT_URI: REDIRECT_URI,
    MIND_GOOGLE_TOKEN_ENCRYPTION_KEY: encryptionKey,
    MIND_GOOGLE_DRIVE_ALLOWED_ORIGINS: LOCAL_ORIGIN,
    API_CORS_ORIGINS: LOCAL_ORIGIN,
  };
}

function runCli(args) {
  const result = spawnSync("npx", ["--yes", `supabase@${CLI_VERSION}`, ...args], {
    cwd: ROOT, encoding: "utf8", maxBuffer: 50 * 1024 * 1024, windowsHide: true,
  });
  if (result.error || result.status !== 0) {
    // CLI status/start output can contain local JWT keys; never echo captured output.
    throw new Error("Supabase local não concluiu o comando. A saída foi suprimida para não expor chaves locais.");
  }
  return result.stdout ?? "";
}

function prepareRuntime() {
  const supabaseDir = join(RUNTIME, "supabase");
  const migrationsDir = join(supabaseDir, "migrations");
  mkdirSync(migrationsDir, { recursive: true });
  writeFileSync(join(supabaseDir, "config.toml"), readFileSync(join(ROOT, "tests", "mind-codespaces", "config.toml")));
  writeFileSync(join(migrationsDir, "20261120190000_mind_codespaces_base.sql"), readFileSync(join(ROOT, "tests", "mind-codespaces", "base-schema.sql")));
  writeFileSync(join(migrationsDir, "20261120191900_mind_google_drive_storage.sql"), readFileSync(join(ROOT, "supabase", "migrations", "20261120191900_mind_google_drive_storage.sql")));
}

function readOrCreateEncryptionKey() {
  if (existsSync(KEY_FILE)) return readFileSync(KEY_FILE, "utf8").trim();
  const key = randomBytes(32).toString("base64");
  writeFileSync(KEY_FILE, key + "\n", { mode: 0o600, flag: "wx" });
  return key;
}

function writeBackendEnv(values) {
  mkdirSync(BACKEND, { recursive: true });
  if (existsSync(ENV_FILE)) {
    const current = readFileSync(ENV_FILE, "utf8");
    if (!current.startsWith(ENV_MARKER)) throw new Error("backend/.env já existe e não é gerenciado por este script; não foi alterado.");
  }
  const contents = ENV_MARKER + Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join("\n") + "\n";
  writeFileSync(ENV_FILE, contents, { mode: 0o600 });
}

export function sanitizedHttpFailure(status, data, failureMessage) {
  const rawCode = data && typeof data === "object" ? (data.error_code ?? data.code) : null;
  const code = typeof rawCode === "string" && /^[a-z0-9_-]{1,64}$/i.test(rawCode) ? rawCode : null;
  return `${failureMessage} (HTTP ${status}${code ? `, código ${code}` : ""}).`;
}

async function fetchJson(url, options, failureMessage) {
  let response;
  try { response = await fetch(url, options); } catch { throw new Error(failureMessage); }
  let data;
  try { data = await response.json(); } catch { data = {}; }
  if (!response.ok) throw new Error(sanitizedHttpFailure(response.status, data, failureMessage));
  return data;
}

async function ensureLocalAdmin(status) {
  const api = status.API_URL;
  const anon = status.ANON_KEY;
  const service = status.SERVICE_ROLE_KEY;
  let account;
  if (existsSync(ADMIN_FILE)) {
    account = JSON.parse(readFileSync(ADMIN_FILE, "utf8"));
  } else {
    account = {
      email: `mind-codespaces-${randomBytes(8).toString("hex")}@example.test`,
      password: randomBytes(36).toString("base64url"),
    };
    const created = await fetchJson(`${api}/auth/v1/admin/users`, {
      method: "POST", headers: { apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json" },
      body: JSON.stringify({ email: account.email, password: account.password, email_confirm: true }),
    }, "Não foi possível criar a conta administrativa de teste local.");
    if (!created.id && !created.user?.id) throw new Error("Supabase Auth local não retornou o identificador do usuário de teste.");
    writeFileSync(ADMIN_FILE, JSON.stringify({ email: account.email, password: account.password }, null, 2) + "\n", { mode: 0o600, flag: "wx" });
  }
  const login = await fetchJson(`${api}/auth/v1/token?grant_type=password`, {
    method: "POST", headers: { apikey: anon, "Content-Type": "application/json" },
    body: JSON.stringify({ email: account.email, password: account.password }),
  }, "A conta local de teste não entrou no Supabase isolado.");
  const signupResponse = await fetch(`${api}/auth/v1/signup`, {
    method: "POST", headers: { apikey: anon, "Content-Type": "application/json" },
    body: JSON.stringify({ email: `mind-codespaces-public-${randomBytes(8).toString("hex")}@example.test`, password: randomBytes(36).toString("base64url") }),
  });
  let signupBody = {};
  try { signupBody = await signupResponse.json(); } catch {}
  const signupCode = signupBody && typeof signupBody === "object" ? (signupBody.error_code ?? signupBody.code) : null;
  if (signupResponse.ok || signupCode !== "signup_disabled") {
    throw new Error(sanitizedHttpFailure(signupResponse.status, signupBody, "O Supabase descartável não confirmou o bloqueio de cadastro público"));
  }
  const accessToken = login.access_token;
  const user = await fetchJson(`${api}/auth/v1/user`, {
    headers: { apikey: anon, Authorization: `Bearer ${accessToken}` },
  }, "Supabase Auth local não validou a sessão de teste.");
  account.id = user.id;
  if (!account.id || !accessToken) throw new Error("Supabase Auth local não retornou a sessão de teste esperada.");
  await fetchJson(`${api}/rest/v1/rpc/mind_codespaces_make_admin`, {
    method: "POST", headers: { apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json" },
    body: JSON.stringify({ p_admin_id: account.id }),
  }, "Não foi possível habilitar o usuário de teste como administrador local.");
  const allowed = await fetchJson(`${api}/rest/v1/rpc/mind_is_admin`, {
    method: "POST", headers: { apikey: anon, Authorization: `Bearer ${accessToken}`, "Content-Type": "application/json" },
    body: "{}",
  }, "PostgREST não confirmou o usuário administrativo local.");
  if (allowed !== true) throw new Error("A verificação administrativa local falhou.");
  const publicItems = await fetchJson(`${api}/rest/v1/mind_items?select=id&limit=4`, {
    headers: { apikey: anon },
  }, "PostgREST não conseguiu ler a biblioteca sintética local.");
  if (!Array.isArray(publicItems) || publicItems.length !== 4) throw new Error("A leitura pública sintética não retornou os quatro itens esperados.");
}

async function up() {
  prepareRuntime();
  runCli(["start", "--workdir", RUNTIME, "--exclude", "studio,inbucket,imgproxy,realtime,functions,analytics,vector,supavisor"]);
  const status = parseSupabaseStatusEnv(runCli(["status", "--workdir", RUNTIME, "-o", "env"]));
  const env = buildLocalBackendEnv(status, process.env, readOrCreateEncryptionKey());
  await ensureLocalAdmin(status);
  writeBackendEnv(env);
  console.log("Supabase local isolado ativo; migrations de teste aplicadas; backend/.env local preparado.");
  console.log(`Conta administrativa descartável: ${ADMIN_FILE}`);
  if (env.MIND_GOOGLE_DRIVE_ENABLED !== "true") console.log("Google Drive permanece desativado: faltam as credenciais OAuth rotacionadas no Codespaces.");
}

function stop() {
  runCli(["stop", "--workdir", RUNTIME]);
  console.log("Supabase local parado. O volume local foi preservado; nenhum comando destrutivo foi usado.");
}

async function status() {
  const env = parseSupabaseStatusEnv(runCli(["status", "--workdir", RUNTIME, "-o", "env"]));
  let response;
  try { response = await fetch(`${env.API_URL}/auth/v1/health`); }
  catch { throw new Error("Supabase Auth local não respondeu pelo loopback."); }
  if (!response.ok) throw new Error(`Supabase Auth local respondeu HTTP ${response.status}.`);
  console.log(`Supabase Auth local: HTTP ${response.status}; nenhuma chave foi exibida.`);
}

export function renderDotEnv(values) {
  return ENV_MARKER + Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join("\n") + "\n";
}

const command = process.argv[2];
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (command === "up") await up();
    else if (command === "stop") stop();
    else if (command === "status") await status();
    else throw new Error("Use: node scripts/mind-codespaces.mjs up|status|stop");
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Falha local sem detalhes sensíveis.");
    process.exitCode = 1;
  }
}
